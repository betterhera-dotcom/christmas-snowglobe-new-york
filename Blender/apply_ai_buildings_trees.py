def digest():
 h=hashlib.sha256()
 for o in sorted(bpy.data.objects,key=lambda x:x.name):
  h.update(str((o.name,o.type,tuple(v for row in o.matrix_world for v in row))).encode())
  if o.type=='MESH':
   for v in o.data.vertices:h.update(str(tuple(v.co)).encode())
 return h.hexdigest()
