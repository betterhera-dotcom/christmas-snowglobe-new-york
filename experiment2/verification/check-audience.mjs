import assert from 'node:assert/strict';
import {AudienceGate} from '../audience.mjs';
import {body,hand} from './body-fixture.mjs';
const gate=new AudienceGate();
for(const size of [.006,.02,.1,.5,.9])assert.equal(gate.update([body(.5,size)],0).allowed,true,'no range limit or calibration at any detectable size');
assert.equal(gate.update([body()],1).allowed,true,'body works with face and legs invisible');
assert.equal(gate.handIndex([hand(.38)],1.1),0);
const hidden=body();hidden[11].visibility=.1;assert.equal(gate.update([hidden],1.2).allowed,false,'unreliable shoulders do not grant control');
gate.reset();
const front=body(.25,.2),rear=body(.75,.1);
assert.equal(gate.update([rear,body(.5,.15),front],2).selected.index,2,'largest projected body wins, regardless of detection order');
assert.equal(gate.handIndex([hand(.69,.38),hand(.13)],2.1),1,'only the front viewer hand is used');
assert.equal(gate.handIndex([hand(.69,.38)],2.1),-1,'rear hand cannot take control when front hand disappears');
assert.equal(gate.update([front,rear],2.2).changed,false,'reordering detections is not a new viewer');
assert.equal(gate.selected.index,0);
assert.equal(gate.update([body(.75,.21),front],2.3).selected.index,1,'small size jitter does not switch viewers');
assert.equal(gate.update([body(.75,.26),front],2.4).changed,true,'clearly larger newcomer takes over');
assert.equal(gate.selected.index,0);assert.equal(gate.handAnchor,null,'handover clears previous hand anchor');
assert.equal(gate.update([front],2.5).changed,true,'remaining viewer selected after the front viewer leaves');
assert.equal(gate.handIndex([hand(.13)],4.9),0);
assert.equal(gate.handIndex([hand(.13)],5.1),-1,'stale body cannot authorize a hand');
assert.equal(gate.update([front],5.2).changed,true,'reacquisition after expiry resets gesture state');
assert.equal(gate.update([],5.3).allowed,false,'explicit body loss stops immediately');
const noWrists=body();noWrists[15].visibility=noWrists[16].visibility=0;gate.update([noWrists],6);
assert.equal(gate.handIndex([hand(.38)],6.1),-1,'invisible wrists cannot claim a hand');
gate.reset();gate.update([body(.5,.2),body(.5,.19)],7);
assert.equal(gate.handIndex([hand(.38)],7.1),-1,'overlapping ambiguous hands do not control');
gate.reset();gate.update([front,rear],8);
const face=(x,y)=>[{x:x-.02,y:y-.02},{x:x+.02,y:y+.02}];
assert.equal(gate.ownsFace(face(.25,.2),8.1),true,'optional city face belongs to selected body');
assert.equal(gate.ownsFace(face(.75,.25),8.1),false,'background face cannot steer the city');
assert.equal(gate.ownsFace(face(.25,.2),11),false,'expired body cannot steer city');
console.log('PASS: no range/calibration, multiple candidates, stable front selection, handover, rear/ambiguous hands, face ownership and expiry');

const moving=new AudienceGate();moving.update([body()],0);
assert.equal(moving.handIndex([hand(.38)],.1),0);
assert.equal(moving.handIndex([hand(.24)],.2,{held:true}),0);
assert.equal(moving.handIndex([hand(.12)],.3,{held:true}),0,'held hand continues beyond the stale body wrist by following recent positions');
assert.equal(moving.handIndex([hand(.12)],.8,{held:true}),-1,'old hand anchor cannot authorize reacquisition');
const fresh=new AudienceGate();fresh.update([body()],0);
assert.equal(fresh.handIndex([hand(.12)],.1,{held:true}),-1,'no prior owned hand means no continuity exception');
const multiple=new AudienceGate();multiple.update([body(),body(.75,.1)],0);
multiple.handIndex([hand(.38)],.1);multiple.handIndex([hand(.24)],.2,{held:true});
assert.equal(multiple.handIndex([hand(.12)],.3,{held:true}),-1,'multiple viewers always require normal ownership checks');
console.log('PASS: bounded held-hand continuity, expiry, acquisition and multi-viewer guards');
