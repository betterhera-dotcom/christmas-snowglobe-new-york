import assert from 'node:assert/strict';
import {AudienceGate} from '../audience.mjs';
const face=(x,size)=>[{x:x-size/2,y:.25-size/2},{x:x+size/2,y:.25-size/2},{x:x+size/2,y:.25+size/2},{x:x-size/2,y:.25+size/2}];
const hand=x=>Array.from({length:21},()=>({x,y:.4,z:0}));
const gate=new AudienceGate();
assert.equal(gate.update([face(.3,.02)],0).allowed,true,'test mode has no distance restriction');
gate.rangeLimited=true;gate.reset();
assert.equal(gate.update([face(.3,.1)],0).allowed,false,'calibration is required');
assert.equal(gate.calibrate(.1),true);
assert.ok(Math.abs(gate.update([face(.3,.1)],.1).distance-2.3)<1e-9);
assert.equal(gate.allowed,true,'optimal 2.3 m is accepted');
assert.equal(gate.update([face(.3,.1*2.3/2.95)],.2).allowed,true,'inside 3 m is accepted');
assert.equal(gate.update([face(.3,.1*2.3/3)],.25).allowed,true,'3 m boundary is inclusive');
assert.equal(gate.update([face(.3,.1*2.3/3.1)],.3).allowed,false,'beyond 3 m is blocked');
gate.reset();gate.update([face(.75,.065),face(.25,.12)],1);
assert.equal(gate.selected.index,1,'nearest face wins regardless of detection order');
assert.equal(gate.handIndex([hand(.75),hand(.25)],1.1),1,'only the selected viewer hand is used');
assert.equal(gate.handIndex([hand(.75)],1.1),-1,'far viewer cannot take over with just a hand');
assert.equal(gate.handIndex([hand(.25)],1.5),-1,'stale face evidence cannot authorize a hand');
assert.equal(gate.update([],1.6).allowed,false,'face loss blocks control immediately');
assert.equal(gate.update([face(.7,.15)],1.7).changed,true,'new viewer resets gestures');
assert.equal(gate.calibrate(NaN),false);
console.log('PASS: calibration required, 2.3 m optimum, 3 m cutoff, nearest viewer, hand ownership, stale/lost face');
