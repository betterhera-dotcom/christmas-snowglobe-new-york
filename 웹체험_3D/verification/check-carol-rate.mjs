import assert from 'node:assert/strict';
import {Carol} from '../audio.js';
const track={playbackRate:1,currentTime:0,dataset:{},addEventListener(type,fn){this[type]=fn;},play:async()=>{},pause(){}};
const city={play:async()=>{},pause(){}};
const carol=new Carol(track,city);
const gain={gain:{setTargetAtTime(){}}};
carol.resumeContext=()=>{carol.context={currentTime:0,state:'running'};carol.melody=gain;carol.songGain=gain;return Promise.resolve();};
await carol.unlockTrack();assert.equal(track.currentTime,0,'unlock keeps the trimmed-file zero-second cue');
track.currentTime=0;track.loadedmetadata();assert.equal(track.currentTime,0,'late metadata restores the cue');
await carol.followShake(.2,true,.3);assert.equal(track.currentTime,0,'song starts at Jingle Bells trimmed-file zero-second cue');
track.currentTime=25;
for(let i=0;i<180;i++)carol.update(1/60,0,'globe');
assert.ok(track.playbackRate>.67&&track.playbackRate<.70,'quiet movement slows recording');
for(let i=0;i<900;i++)carol.update(1/60,.85,'globe');
assert.ok(track.playbackRate>1.14&&track.playbackRate<=1.15,'strong movement speeds recording');
assert.equal(track.currentTime,25,'rate changes never restart recording');
track.ended();assert.equal(track.currentTime,0,'repeat starts from same cue');
assert.equal(city.playbackRate,1,'city music stays at normal speed');
carol.reset();assert.equal(track.currentTime,0,'reset prepares the cue');
console.log('PASS: trimmed-file zero-second start/repeat, smooth slow/fast rates, no seeking, normal city music');
